"""VISIBILITY1 Task 1c/1d — every route, and how staff family visibility applies to it.

    python3 apps/api/scripts/visibility1_routes.py           # write docs/VISIBILITY1_ROUTES.md
    python3 apps/api/scripts/visibility1_routes.py --check   # exit 1 if the doc is stale

Read off the real app (main.app, flattened through the lazy _IncludedRouter wrappers) and each endpoint's source.
Classification, in order (a route may carry several):
  guard:<param>   the app-wide family_path_guard 404s an invisible family's id in the path (every method)
  sql-scope       the handler filters IN SQL with the shared scope (member_entity_scope / entity_scope /
                  require_entity_access / visible_household_ids / scope_for_request / scope_for_principal)
  body-check      a write naming family ids in its body (require_visible)
  legacy-rule     the legacy resolver (get_staff_visible_entity_ids / visible_entity_ids) — switches to the rule
  scrub           any JSON 2xx response for a restricted caller has rows of invisible families removed
                  (main.rls_context_middleware) — the backstop for every list
"""

from __future__ import annotations

import inspect
import os
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
API = HERE.parent
REPO = API.parents[1]
for _site in sorted(API.glob("venv/lib/python3*/site-packages")):
    sys.path.insert(0, str(_site))
sys.path.insert(0, str(API))
os.environ.setdefault("AUTHZ_TEST_MODE", "1")

import main  # noqa: E402
from services import family_visibility as FV  # noqa: E402

DOC = REPO / "docs" / "VISIBILITY1_ROUTES.md"
SQL_MARKERS = ("member_entity_scope", "entity_scope(", "require_entity_access", "visible_household_ids",
               "scope_for_request", "scope_for_principal", "_visible_households", "_require_household(")
LEGACY = ("get_staff_visible_entity_ids", "visible_entity_ids(", "staff_tree(")


def _walk(routes, prefix=""):
    for r in routes:
        if hasattr(r, "original_router"):
            yield from _walk(r.original_router.routes, prefix + r.include_context.prefix)
        elif hasattr(r, "endpoint") and hasattr(r, "methods"):
            yield prefix + r.path, r


def _guard_params(path: str) -> list[str]:
    out = []
    for name in ("entity_id", "household_id", "account_id", *[k for k in FV._RESOLVERS if k != "account_id"]):
        if "{" + name + "}" not in path:
            continue
        if any(path.startswith(px) for px in FV._NOT_FAMILY.get(name, ())):
            continue
        spec = FV._RESOLVERS.get(name)
        if spec and spec[0] is not None and not any(path.startswith(px) for px in spec[0]):
            continue
        out.append(name)
    return out


def classify(path: str, route) -> list[str]:
    try:
        src = inspect.getsource(route.endpoint)
    except (OSError, TypeError):
        src = ""
    tags = [f"guard:{p}" for p in _guard_params(path)]
    if any(m in src for m in SQL_MARKERS):
        tags.append("sql-scope")
    if "require_visible(" in src:
        tags.append("body-check")
    if any(m in src for m in LEGACY):
        tags.append("legacy-rule")
    tags.append("scrub")
    return tags


def render() -> str:
    rows = []
    for path, route in _walk(main.app.routes):
        if not path.startswith("/api/v1/"):
            continue
        for m in sorted(route.methods - {"HEAD", "OPTIONS"}):
            rows.append((path, m, route.endpoint.__module__.split(".")[-1], classify(path, route)))
    rows.sort()
    counts = {"guard": 0, "sql-scope": 0, "body-check": 0, "legacy-rule": 0}
    for _p, _m, _mod, tags in rows:
        for k in counts:
            if any(t == k or t.startswith(k + ":") for t in tags):
                counts[k] += 1
    lines = [
        "# VISIBILITY1 — routes and staff family visibility",
        "",
        "Generated by `apps/api/scripts/visibility1_routes.py` from the real app (`--check` fails when stale).",
        "Applies only to a RESTRICTED caller: an internal staff user of an org whose `staff_visibility.enforced`",
        "is true, who is not Super Admin and not org admin. For everyone else every route is unchanged.",
        "",
        "| tag | meaning |",
        "|---|---|",
        "| guard:&lt;param&gt; | the app-wide `family_path_guard` returns the same 404 as a missing id (all methods) |",
        "| sql-scope | the handler filters in SQL with the shared scope (one `= ANY($n::uuid[])`) |",
        "| body-check | a write naming family ids in its body refuses an invisible one (`require_visible`) |",
        "| legacy-rule | uses the legacy resolver, which follows the rule when the switch is on |",
        "| scrub | the JSON response has every row of an invisible family removed (backstop on EVERY route) |",
        "",
        f"Routes: {len(rows)} · guarded {counts['guard']} · sql-scope {counts['sql-scope']} · "
        f"body-check {counts['body-check']} · legacy-rule {counts['legacy-rule']}",
        "",
        "| method | path | module | visibility |",
        "|---|---|---|---|",
    ]
    for path, m, mod, tags in rows:
        lines.append(f"| {m} | `{path}` | {mod} | {', '.join(tags)} |")
    return "\n".join(lines) + "\n"


def main_cli() -> int:
    text = render()
    if "--check" in sys.argv:
        current = DOC.read_text() if DOC.exists() else ""
        print("CURRENT" if current == text else "STALE")
        return 0 if current == text else 1
    DOC.write_text(text)
    print(f"wrote {DOC.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main_cli())
